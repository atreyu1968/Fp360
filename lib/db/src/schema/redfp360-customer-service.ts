import {
  boolean,
  date,
  index,
  integer,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
} from "drizzle-orm/pg-core";
import { fpOrganizations, fpLogisticsShipmentLines, fpLogisticsShipments } from "./redfp360";

export const fpCustomerCases = pgTable(
  "fp360_customer_cases",
  {
    id: text("id").primaryKey(),
    tenantId: text("tenant_id").notNull(),
    organizationId: text("organization_id").notNull().references(() => fpOrganizations.id),
    customerOrganizationId: text("customer_organization_id").notNull().references(() => fpOrganizations.id),
    caseRef: text("case_ref").notNull(),
    sourceType: text("source_type").notNull(),
    sourceReference: text("source_reference"),
    category: text("category").notNull(),
    priority: text("priority").notNull(),
    status: text("status").notNull().default("draft"),
    request: text("request").notNull(),
    standaloneReason: text("standalone_reason"),
    assignedToUserId: text("assigned_to_user_id"),
    assignedToName: text("assigned_to_name"),
    proposedSolution: text("proposed_solution"),
    rootCause: text("root_cause"),
    satisfactionScore: integer("satisfaction_score"),
    openedDate: date("opened_date", { mode: "string" }).notNull(),
    dueDate: date("due_date", { mode: "string" }),
    resolvedAt: timestamp("resolved_at", { withTimezone: true }),
    closedAt: timestamp("closed_at", { withTimezone: true }),
    operationId: text("operation_id").notNull(),
    requestFingerprint: text("request_fingerprint").notNull(),
    createdByUserId: text("created_by_user_id").notNull(),
    createdByName: text("created_by_name").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    uniqueIndex("fp360_customer_case_ref_unique").on(table.tenantId, table.organizationId, table.caseRef),
    uniqueIndex("fp360_customer_case_operation_unique").on(table.tenantId, table.operationId),
    index("fp360_customer_case_org_status_idx").on(table.tenantId, table.organizationId, table.status),
    index("fp360_customer_case_customer_idx").on(table.tenantId, table.customerOrganizationId),
  ],
);

export const fpCustomerCaseEvents = pgTable(
  "fp360_customer_service_events",
  {
    id: text("id").primaryKey(),
    tenantId: text("tenant_id").notNull(),
    organizationId: text("organization_id").notNull().references(() => fpOrganizations.id),
    entityType: text("entity_type").notNull(),
    entityId: text("entity_id").notNull(),
    caseId: text("case_id").references(() => fpCustomerCases.id),
    eventType: text("event_type").notNull(),
    description: text("description").notNull(),
    reference: text("reference"),
    actorUserId: text("actor_user_id").notNull(),
    actorName: text("actor_name").notNull(),
    operationId: text("operation_id").notNull(),
    requestFingerprint: text("request_fingerprint").notNull(),
    simulatedDate: date("simulated_date", { mode: "string" }).notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    uniqueIndex("fp360_customer_service_event_operation_unique").on(table.tenantId, table.operationId),
    index("fp360_customer_service_events_entity_idx").on(table.tenantId, table.entityType, table.entityId, table.createdAt),
    index("fp360_customer_service_events_case_idx").on(table.tenantId, table.caseId, table.createdAt),
  ],
);

export const fpCustomerReturns = pgTable(
  "fp360_customer_returns",
  {
    id: text("id").primaryKey(),
    tenantId: text("tenant_id").notNull(),
    organizationId: text("organization_id").notNull().references(() => fpOrganizations.id),
    caseId: text("case_id").notNull().references(() => fpCustomerCases.id),
    shipmentId: text("shipment_id").notNull().references(() => fpLogisticsShipments.id),
    shipmentLineId: text("shipment_line_id").notNull().references(() => fpLogisticsShipmentLines.id),
    returnRef: text("return_ref").notNull(),
    productId: text("product_id").notNull(),
    productName: text("product_name").notNull(),
    unitsDelivered: integer("units_delivered").notNull(),
    unitsReported: integer("units_reported").notNull(),
    unitsApproved: integer("units_approved").notNull().default(0),
    unitsReceived: integer("units_received").notNull().default(0),
    condition: text("condition").notNull(),
    reason: text("reason").notNull(),
    status: text("status").notNull().default("requested"),
    creditNoteRequested: boolean("credit_note_requested").notNull().default(false),
    operationId: text("operation_id").notNull(),
    requestFingerprint: text("request_fingerprint").notNull(),
    createdByUserId: text("created_by_user_id").notNull(),
    createdByName: text("created_by_name").notNull(),
    reviewedByUserId: text("reviewed_by_user_id"),
    reviewedByName: text("reviewed_by_name"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    uniqueIndex("fp360_customer_return_ref_unique").on(table.tenantId, table.organizationId, table.returnRef),
    uniqueIndex("fp360_customer_return_operation_unique").on(table.tenantId, table.operationId),
    index("fp360_customer_returns_case_idx").on(table.tenantId, table.caseId),
    index("fp360_customer_returns_shipment_line_idx").on(table.tenantId, table.shipmentLineId),
  ],
);

export const fpCustomerAgreements = pgTable(
  "fp360_customer_agreements",
  {
    id: text("id").primaryKey(),
    tenantId: text("tenant_id").notNull(),
    organizationId: text("organization_id").notNull().references(() => fpOrganizations.id),
    agreementRef: text("agreement_ref").notNull(),
    productRef: text("product_ref").notNull(),
    terms: text("terms").notNull(),
    validFrom: date("valid_from", { mode: "string" }).notNull(),
    validTo: date("valid_to", { mode: "string" }).notNull(),
    replacementAllowed: boolean("replacement_allowed").notNull().default(false),
    compensationAllowed: boolean("compensation_allowed").notNull().default(false),
    status: text("status").notNull().default("draft"),
    operationId: text("operation_id").notNull(),
    requestFingerprint: text("request_fingerprint").notNull(),
    createdByUserId: text("created_by_user_id").notNull(),
    createdByName: text("created_by_name").notNull(),
    approvedByUserId: text("approved_by_user_id"),
    approvedByName: text("approved_by_name"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    approvedAt: timestamp("approved_at", { withTimezone: true }),
  },
  (table) => [
    uniqueIndex("fp360_customer_agreement_ref_unique").on(table.tenantId, table.organizationId, table.agreementRef),
    uniqueIndex("fp360_customer_agreement_operation_unique").on(table.tenantId, table.operationId),
    index("fp360_customer_agreements_org_status_idx").on(table.tenantId, table.organizationId, table.status),
  ],
);
