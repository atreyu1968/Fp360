import {
  boolean,
  date,
  index,
  integer,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
} from "drizzle-orm/pg-core";
import { fpOrganizations, fpOrders, fpPurchaseReceiptLines } from "./redfp360";

export const fpProjects = pgTable(
  "fp360_projects",
  {
    id: text("id").primaryKey(),
    tenantId: text("tenant_id").notNull(),
    organizationId: text("organization_id").notNull().references(() => fpOrganizations.id),
    customerOrganizationId: text("customer_organization_id").references(() => fpOrganizations.id),
    projectRef: text("project_ref").notNull(),
    projectType: text("project_type").notNull(),
    title: text("title").notNull(),
    objective: text("objective").notNull(),
    scope: text("scope").notNull(),
    budgetMinutes: integer("budget_minutes").notNull(),
    budgetAmountCents: integer("budget_amount_cents").notNull(),
    startDate: date("start_date", { mode: "string" }).notNull(),
    endDate: date("end_date", { mode: "string" }).notNull(),
    status: text("status").notNull().default("draft"),
    version: integer("version").notNull().default(1),
    operationId: text("operation_id").notNull(),
    requestFingerprint: text("request_fingerprint").notNull(),
    createdByUserId: text("created_by_user_id").notNull(),
    createdByName: text("created_by_name").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
    completedAt: timestamp("completed_at", { withTimezone: true }),
    closedAt: timestamp("closed_at", { withTimezone: true }),
  },
  (table) => [
    uniqueIndex("fp360_project_ref_unique").on(table.tenantId, table.organizationId, table.projectRef),
    uniqueIndex("fp360_project_operation_unique").on(table.tenantId, table.operationId),
    index("fp360_projects_org_status_idx").on(table.tenantId, table.organizationId, table.status),
  ],
);

