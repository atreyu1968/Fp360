import {
  boolean,
  date,
  index,
  integer,
  jsonb,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
} from "drizzle-orm/pg-core";
import { fpOrganizations } from "./redfp360";

export const fpTaxDeclarations = pgTable(
  "fp360_tax_declarations",
  {
    id: text("id").primaryKey(),
    tenantId: text("tenant_id").notNull(),
    organizationId: text("organization_id").notNull().references(() => fpOrganizations.id),
    taxType: text("tax_type").notNull(),
    modelCode: text("model_code").notNull(),
    periodKey: text("period_key").notNull(),
    periodStart: date("period_start", { mode: "string" }).notNull(),
    periodEnd: date("period_end", { mode: "string" }).notNull(),
    simulatedDueDate: date("simulated_due_date", { mode: "string" }),
    version: integer("version").notNull().default(1),
    status: text("status").notNull().default("draft"),
    paymentStatus: text("payment_status").notNull().default("not_due"),
    sourceInvoiceIds: jsonb("source_invoice_ids").$type<string[]>().notNull().default([]),
    sourcePurchaseInvoiceIds: jsonb("source_purchase_invoice_ids").$type<string[]>().notNull().default([]),
    formData: jsonb("form_data").$type<Record<string, string>>().notNull().default({}),
    taxableBaseCents: integer("taxable_base_cents").notNull().default(0),
    outputIgicCents: integer("output_igic_cents").notNull().default(0),
    inputIgicCents: integer("input_igic_cents").notNull().default(0),
    withholdingBaseCents: integer("withholding_base_cents").notNull().default(0),
    withholdingCents: integer("withholding_cents").notNull().default(0),
    resultCents: integer("result_cents").notNull().default(0),
    receiptReference: text("receipt_reference"),
    supersedesId: text("supersedes_id"),
    operationId: text("operation_id").notNull(),
    requestFingerprint: text("request_fingerprint").notNull(),
    createdByUserId: text("created_by_user_id").notNull(),
    createdByName: text("created_by_name").notNull(),
    lastActionByUserId: text("last_action_by_user_id"),
    lastActionByName: text("last_action_by_name"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
    sourcePayrollRunIds: jsonb("source_payroll_run_ids").$type<string[]>(),
  },
  (table) => [
    uniqueIndex("fp360_tax_declaration_operation_idx").on(table.tenantId, table.operationId),
    uniqueIndex("fp360_tax_declaration_version_idx").on(
      table.tenantId,
      table.organizationId,
      table.taxType,
      table.modelCode,
      table.periodKey,
      table.version,
    ),
    index("fp360_tax_declaration_org_idx").on(table.tenantId, table.organizationId, table.status),
    index("fp360_tax_declaration_period_idx").on(table.tenantId, table.organizationId, table.periodKey),
  ],
);

export const fpTaxProfiles = pgTable(
  "fp360_tax_profiles",
  {
    id: text("id").primaryKey(),
    tenantId: text("tenant_id").notNull(),
    organizationId: text("organization_id").notNull().references(() => fpOrganizations.id),
    entityType: text("entity_type").notNull(),
    igicRegime: text("igic_regime").notNull(),
    incomeTaxMethod: text("income_tax_method").notNull(),
    hasEmployees: boolean("has_employees").notNull().default(false),
    withholdsProfessionals: boolean("withholds_professionals").notNull().default(false),
    paysBusinessRent: boolean("pays_business_rent").notNull().default(false),
    updatedByUserId: text("updated_by_user_id").notNull(),
    updatedByName: text("updated_by_name").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    uniqueIndex("fp360_tax_profile_org_idx").on(table.tenantId, table.organizationId),
  ],
);

export const fpTaxRequirements = pgTable(
  "fp360_tax_requirements",
  {
    id: text("id").primaryKey(),
    tenantId: text("tenant_id").notNull(),
    organizationId: text("organization_id").notNull().references(() => fpOrganizations.id),
    declarationId: text("declaration_id").notNull().references(() => fpTaxDeclarations.id),
    reference: text("reference").notNull(),
    title: text("title").notNull(),
    detail: text("detail").notNull(),
    status: text("status").notNull().default("open"),
    response: text("response"),
    operationId: text("operation_id").notNull(),
    requestFingerprint: text("request_fingerprint").notNull(),
    createdByUserId: text("created_by_user_id").notNull(),
    createdByName: text("created_by_name").notNull(),
    respondedByUserId: text("responded_by_user_id"),
    respondedByName: text("responded_by_name"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    uniqueIndex("fp360_tax_requirement_reference_idx").on(table.tenantId, table.reference),
    uniqueIndex("fp360_tax_requirement_operation_idx").on(table.tenantId, table.operationId),
    index("fp360_tax_requirement_org_idx").on(table.tenantId, table.organizationId, table.status),
  ],
);

export const fpTaxEvents = pgTable(
  "fp360_tax_events",
  {
    id: text("id").primaryKey(),
    tenantId: text("tenant_id").notNull(),
    organizationId: text("organization_id").notNull().references(() => fpOrganizations.id),
    declarationId: text("declaration_id").references(() => fpTaxDeclarations.id),
    requirementId: text("requirement_id").references(() => fpTaxRequirements.id),
    operationId: text("operation_id").notNull(),
    requestFingerprint: text("request_fingerprint").notNull(),
    eventType: text("event_type").notNull(),
    description: text("description").notNull(),
    actorUserId: text("actor_user_id").notNull(),
    actorName: text("actor_name").notNull(),
    simulatedDate: date("simulated_date", { mode: "string" }).notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    uniqueIndex("fp360_tax_event_operation_idx").on(table.tenantId, table.operationId),
    index("fp360_tax_event_org_idx").on(table.tenantId, table.organizationId, table.createdAt),
  ],
);
