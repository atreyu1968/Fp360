import {
  boolean,
  date,
  index,
  integer,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
} from "drizzle-orm/pg-core";
import { fpOrganizations } from "./redfp360";

export const fpDocumentDossiers = pgTable(
  "fp360_document_dossiers",
  {
    id: text("id").primaryKey(),
    tenantId: text("tenant_id").notNull(),
    organizationId: text("organization_id").notNull().references(() => fpOrganizations.id),
    dossierRef: text("dossier_ref").notNull(),
    title: text("title").notNull(),
    dossierType: text("dossier_type").notNull(),
    department: text("department").notNull(),
    period: text("period").notNull(),
    status: text("status").notNull().default("open"),
    retentionRule: text("retention_rule").notNull().default("educational"),
    createdByUserId: text("created_by_user_id").notNull(),
    createdByName: text("created_by_name").notNull(),
    operationId: text("operation_id").notNull(),
    requestFingerprint: text("request_fingerprint").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
    archivedAt: timestamp("archived_at", { withTimezone: true }),
  },
  (table) => [
    uniqueIndex("fp360_document_dossier_ref_unique").on(table.tenantId, table.organizationId, table.dossierRef),
    uniqueIndex("fp360_document_dossier_operation_unique").on(table.tenantId, table.operationId),
    index("fp360_document_dossiers_scope_idx").on(table.tenantId, table.organizationId, table.status),
  ],
);

export const fpDocuments = pgTable(
  "fp360_documents",
  {
    id: text("id").primaryKey(),
    tenantId: text("tenant_id").notNull(),
    organizationId: text("organization_id").notNull().references(() => fpOrganizations.id),
    dossierId: text("dossier_id").notNull().references(() => fpDocumentDossiers.id),
    documentRef: text("document_ref").notNull(),
    documentType: text("document_type").notNull(),
    title: text("title").notNull(),
    description: text("description").notNull().default(""),
    department: text("department").notNull(),
    period: text("period").notNull(),
    documentDate: date("document_date", { mode: "string" }).notNull(),
    status: text("status").notNull().default("draft"),
    visibility: text("visibility").notNull().default("organization"),
    ownerUserId: text("owner_user_id").notNull(),
    ownerName: text("owner_name").notNull(),
    originApp: text("origin_app").notNull().default("manual"),
    originId: text("origin_id"),
    rectifiesDocumentId: text("rectifies_document_id"),
    tags: text("tags").notNull().default(""),
    versionNumber: integer("version_number").notNull().default(0),
    isSynthetic: boolean("is_synthetic").notNull().default(true),
    operationId: text("operation_id").notNull(),
    requestFingerprint: text("request_fingerprint").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
    archivedAt: timestamp("archived_at", { withTimezone: true }),
  },
  (table) => [
    uniqueIndex("fp360_document_ref_unique").on(table.tenantId, table.organizationId, table.documentRef),
    uniqueIndex("fp360_document_operation_unique").on(table.tenantId, table.operationId),
    index("fp360_documents_scope_status_idx").on(table.tenantId, table.organizationId, table.status),
    index("fp360_documents_dossier_idx").on(table.tenantId, table.dossierId, table.documentDate),
  ],
);

export const fpDocumentVersions = pgTable(
  "fp360_document_versions",
  {
    id: text("id").primaryKey(),
    tenantId: text("tenant_id").notNull(),
    organizationId: text("organization_id").notNull().references(() => fpOrganizations.id),
    documentId: text("document_id").notNull().references(() => fpDocuments.id),
    versionNumber: integer("version_number").notNull(),
    status: text("status").notNull().default("pending_upload"),
    objectPath: text("object_path"),
    originalName: text("original_name"),
    contentType: text("content_type").notNull(),
    sizeBytes: integer("size_bytes").notNull().default(0),
    checksumSha256: text("checksum_sha256"),
    contentText: text("content_text"),
    description: text("description").notNull().default(""),
    sourceVersionId: text("source_version_id"),
    createdByUserId: text("created_by_user_id").notNull(),
    createdByName: text("created_by_name").notNull(),
    operationId: text("operation_id").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    uniqueIndex("fp360_document_version_number_unique").on(table.tenantId, table.documentId, table.versionNumber),
    uniqueIndex("fp360_document_version_operation_unique").on(table.tenantId, table.operationId),
    index("fp360_document_versions_document_idx").on(table.tenantId, table.documentId, table.versionNumber),
  ],
);

export const fpDocumentEvents = pgTable(
  "fp360_document_events",
  {
    id: text("id").primaryKey(),
    tenantId: text("tenant_id").notNull(),
    organizationId: text("organization_id").notNull().references(() => fpOrganizations.id),
    dossierId: text("dossier_id").references(() => fpDocumentDossiers.id),
    documentId: text("document_id").references(() => fpDocuments.id),
    versionId: text("version_id").references(() => fpDocumentVersions.id),
    eventType: text("event_type").notNull(),
    details: text("details").notNull(),
    actorUserId: text("actor_user_id").notNull(),
    actorName: text("actor_name").notNull(),
    simulatedDate: date("simulated_date", { mode: "string" }).notNull(),
    operationId: text("operation_id").notNull(),
    requestFingerprint: text("request_fingerprint").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    uniqueIndex("fp360_document_event_operation_unique").on(table.tenantId, table.operationId),
    index("fp360_document_events_scope_date_idx").on(table.tenantId, table.organizationId, table.createdAt),
    index("fp360_document_events_document_idx").on(table.tenantId, table.documentId, table.createdAt),
  ],
);
